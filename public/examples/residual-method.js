#!/usr/bin/env node
// residual-method.js: the residual method behind the Geometric Encapsulation Protocol, in one file.
//
//   1. A short RULE predicts every byte of the data (here, the saddle z = x*y and a Schwarz D slice).
//   2. The RESIDUAL is the exact difference between the data and the prediction, byte by byte (mod 256),
//      so rebuilding is always lossless: prediction + residual = the original, checked with SHA-256.
//   3. Each residual byte is stored as its difference from the byte above it (the "neighbour delta",
//      the same idea as PNG's Up filter). Where the rule predicts well, the residual is almost all zeros,
//      and what is left sits along edges and lines, so the deltas are smaller still.
//   4. A standard compressor packs what is left. The capsule is: rule + packed residual.
//
// It is compared against the best existing lossless methods tried here: brotli, deflate and zstd
// (when this Node has it), each on the raw bytes and on PNG-style Up and Paeth filtered bytes.
//
// Honest limits, printed with the results: the test fields are generated by the same rules, so they are
// the best case by design; the rule is chosen by hand for each field, not discovered; random data has no
// rule, and there the method loses slightly and should not be used.
//
//   node residual-method.js            (Node 18 or later, no packages)
'use strict';
const zlib = require('zlib');
const crypto = require('crypto');
const W = 256, H = 256;
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex').slice(0, 16);

// ---- rules: each builds the whole field from a few numbers
const RULES = {
  saddle: ({ ax, ay }) => field((i, j) => {
    const x = (i / W * 2 - 1) * ax, y = (j / H * 2 - 1) * ay;
    return Math.max(0, Math.min(255, Math.round((x * y + 1) / 2 * 255)));
  }),
  schwarz: ({ z0, scale }) => field((i, j) => {
    const x = i * scale, y = j * scale, z = z0;
    const f = Math.sin(x) * Math.sin(y) * Math.sin(z) + Math.sin(x) * Math.cos(y) * Math.cos(z)
            + Math.cos(x) * Math.sin(y) * Math.cos(z) + Math.cos(x) * Math.cos(y) * Math.sin(z);
    return Math.round((f + 2) / 4 * 255);
  }),
};
function field(at) {
  const out = Buffer.alloc(W * H);
  for (let j = 0; j < H; j++) for (let i = 0; i < W; i++) out[j * W + i] = at(i, j);
  return out;
}

// ---- the residual method
const residualOf = (data, guess) => data.map((v, k) => (v - guess[k]) & 0xff);
const upDelta = (buf) => buf.map((v, k) => (k < W ? v : (v - buf[k - W]) & 0xff));
function undoUpDelta(buf) {
  const out = Buffer.from(buf);
  for (let k = W; k < out.length; k++) out[k] = (out[k] + out[k - W]) & 0xff;
  return out;
}

// ---- compressors and PNG-style filters, for the fair baseline
const PACKERS = { deflate: (b) => zlib.deflateRawSync(b, { level: 9 }), brotli: (b) => zlib.brotliCompressSync(b, { params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 11 } }) };
if (zlib.zstdCompressSync) PACKERS.zstd = (b) => zlib.zstdCompressSync(b, { params: { [zlib.constants.ZSTD_c_compressionLevel]: 19 } });
const UNPACK = { deflate: (b) => zlib.inflateRawSync(b), brotli: (b) => zlib.brotliDecompressSync(b), zstd: (b) => zlib.zstdDecompressSync(b) };
function paeth(buf) {
  const out = Buffer.alloc(buf.length);
  for (let k = 0; k < buf.length; k++) {
    const i = k % W, a = i ? buf[k - 1] : 0, b = k >= W ? buf[k - W] : 0, c = i && k >= W ? buf[k - W - 1] : 0;
    const p = a + b - c, pa = Math.abs(p - a), pb = Math.abs(p - b), pc = Math.abs(p - c);
    out[k] = (buf[k] - (pa <= pb && pa <= pc ? a : pb <= pc ? b : c)) & 0xff;
  }
  return out;
}
function bestExisting(data) {
  let best = { size: Infinity };
  for (const [filter, f] of [['none', (b) => b], ['Up', upDelta], ['Paeth', paeth]])
    for (const [name, pack] of Object.entries(PACKERS)) {
      const size = pack(f(data)).length;
      if (size < best.size) best = { size, how: name + (filter === 'none' ? '' : ' + ' + filter) };
    }
  return best;
}

// ---- encode, decode, verify
function capsule(data, rule) {
  const ruleBytes = Buffer.byteLength(JSON.stringify(rule));
  const residual = upDelta(residualOf(data, RULES[rule.type](rule)));
  let best = null;
  for (const [name, pack] of Object.entries(PACKERS)) {
    const packed = pack(residual);
    if (!best || packed.length < best.packed.length) best = { name, packed };
  }
  const rebuilt = RULES[rule.type](rule);
  const res = undoUpDelta(UNPACK[best.name](best.packed));
  for (let k = 0; k < rebuilt.length; k++) rebuilt[k] = (rebuilt[k] + res[k]) & 0xff;
  return { size: ruleBytes + best.packed.length, ruleBytes, residualBytes: best.packed.length, lossless: sha(rebuilt) === sha(data) };
}

const saddle = { type: 'saddle', ax: 3, ay: 3 };
const schwarz = { type: 'schwarz', z0: 0.6, scale: 0.05 };
const rippled = RULES.saddle(saddle).map((v, k) => (v + Math.round(20 * Math.sin((k % W) / 8))) & 0xff);
const CASES = [
  ['saddle field', RULES.saddle(saddle), saddle],
  ['Schwarz D slice', RULES.schwarz(schwarz), schwarz],
  ['saddle plus a ripple the rule does not know', rippled, saddle],
  ['random bytes (no rule fits)', crypto.randomBytes(W * H), saddle],
];

console.log(`\nResidual method vs the best existing lossless method tried, on ${W}x${H} byte fields (${W * H} bytes raw)\n`);
for (const [name, data, rule] of CASES) {
  const best = bestExisting(data), cap = capsule(data, rule);
  const ratio = best.size / cap.size;
  console.log(`  ${name}`);
  console.log(`    best existing : ${String(best.size).padStart(6)} bytes  (${best.how})`);
  console.log(`    capsule       : ${String(cap.size).padStart(6)} bytes  (rule ${cap.ruleBytes} + residual ${cap.residualBytes}), lossless: ${cap.lossless ? 'yes' : 'NO'}`);
  console.log(`    result        : ${ratio >= 1 ? ratio.toFixed(1) + 'x smaller than the best existing' : 'larger than the best existing; use the existing method'}\n`);
}
console.log('Limits: these fields are generated by the same rules (best case by design); the rule is chosen by');
console.log('hand, not discovered; real data must be measured type by type against its own best method.\n');
